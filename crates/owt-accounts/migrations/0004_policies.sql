-- owt-accounts 0004: site policies (owt_accounts::policies): the versions of each
-- document an app asks people to agree to (its terms, its privacy notice), and who
-- agreed to which. Copy this file into the app's migrations directory after 0003,
-- unaltered. It seeds no document: the app publishes its own text.

-- One version of one document. A draft until published; publishing numbers it
-- (1, 2, 3... per document) and records the SHA-256 of its text.
CREATE TABLE policy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The document, as the app's policies::Document names it: its slug and path.
    kind text NOT NULL CHECK (kind ~ '^[a-z][a-z0-9-]{0,31}$'),
    version integer CHECK (version > 0),
    title text NOT NULL CHECK (btrim(title) <> ''),
    -- Empty only while a draft: a document's first draft starts blank.
    body_markdown text NOT NULL,
    -- What changed, shown to people asked to agree to this version.
    summary text NOT NULL DEFAULT '',
    -- The "last updated" date the document shows.
    effective_date date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by bigint REFERENCES accounts ON DELETE SET NULL,
    published_at timestamptz,
    content_sha256 text CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    UNIQUE (kind, version),
    CHECK ((version IS NULL) = (published_at IS NULL)),
    CHECK ((published_at IS NULL) = (content_sha256 IS NULL)),
    CHECK (published_at IS NULL OR btrim(body_markdown) <> '')
);

-- A published version is text someone may have agreed to: it never changes.
CREATE FUNCTION policy_versions_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.published_at IS NOT NULL THEN
        RAISE EXCEPTION 'policy % version % is published and cannot be changed', OLD.kind, OLD.version;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER policy_versions_immutable BEFORE UPDATE ON policy_versions
    FOR EACH ROW EXECUTE FUNCTION policy_versions_immutable();

-- The current version of a document is never deleted; an older one can be, once no
-- account's latest acceptance is that version (policy_acceptances restricts it).
CREATE FUNCTION policy_versions_keep_current() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.published_at IS NOT NULL AND OLD.version = (
        SELECT max(version) FROM policy_versions WHERE kind = OLD.kind AND published_at IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'policy % version % is current and cannot be deleted', OLD.kind, OLD.version;
    END IF;
    RETURN OLD;
END $$;
CREATE TRIGGER policy_versions_keep_current BEFORE DELETE ON policy_versions
    FOR EACH ROW EXECUTE FUNCTION policy_versions_keep_current();

-- Each account's latest acceptance of each document. RESTRICT is the retention rule:
-- a version stays while somebody last agreed to it.
CREATE TABLE policy_acceptances (
    account_id bigint NOT NULL REFERENCES accounts ON DELETE CASCADE,
    kind text NOT NULL,
    version_id bigint NOT NULL REFERENCES policy_versions ON DELETE RESTRICT,
    accepted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (account_id, kind)
);
CREATE INDEX policy_acceptances_version ON policy_acceptances (version_id);

-- Every acceptance, append-only. The version's number and hash rather than a foreign
-- key, so removing an old version keeps the history.
CREATE TABLE policy_acceptance_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts ON DELETE CASCADE,
    kind text NOT NULL,
    version integer NOT NULL,
    content_sha256 text NOT NULL,
    accepted_at timestamptz NOT NULL DEFAULT now(),
    ip text,
    user_agent text CHECK (length(user_agent) <= 512)
);
CREATE INDEX policy_acceptance_events_account ON policy_acceptance_events (account_id, accepted_at);
