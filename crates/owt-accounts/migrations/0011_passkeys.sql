-- owt-accounts 0011: passkeys (WebAuthn) as a second factor (owt_accounts::mfa::passkey).
-- Copy this file into the app's migrations directory as its next unused version,
-- unaltered, if the app keeps copies.
--
-- Schema only: three new tables and a nullable column on `accounts`, nothing rewritten.

SET LOCAL lock_timeout = '5s';

-- The WebAuthn user handle of an account: random, made at its first passkey, and the
-- same for every passkey it registers. An authenticator stores it with a discoverable
-- credential and returns it at sign-in, so it names the account without its username.
CREATE TABLE account_webauthn_users (
    account_id bigint PRIMARY KEY REFERENCES accounts ON DELETE CASCADE,
    user_handle uuid NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One row per registered passkey. `credential_id` is unique across every account: the
-- same credential is never registered twice, and an assertion names its row by it.
-- `passkey` is webauthn-rs's serialized Passkey (public key, counter, backup flags):
-- it holds no secret. `counter`, `backup_eligible` and `backup_state` repeat what it
-- holds, for the settings page and for queries. `disabled_at` is set when an answer's
-- counter suggests the credential was copied: a disabled passkey is no factor (it is
-- not offered, not accepted and not counted) until its owner removes it.
CREATE TABLE account_passkeys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts ON DELETE CASCADE,
    credential_id bytea NOT NULL UNIQUE
        CHECK (octet_length(credential_id) BETWEEN 1 AND 1023),
    passkey jsonb NOT NULL,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 64),
    counter bigint NOT NULL DEFAULT 0 CHECK (counter >= 0),
    backup_eligible boolean NOT NULL DEFAULT false,
    backup_state boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    disabled_at timestamptz
);
CREATE INDEX account_passkeys_account ON account_passkeys (account_id);

-- A registration or authentication begun and not yet finished: webauthn-rs's ceremony
-- state, held here and never by the browser. The browser holds only a random token,
-- whose SHA-256 is `token_hash`. A ceremony is bound to the account, the purpose and
-- the session that began it (`session_hash`, the SHA-256 of the session id), and is
-- answered from that session only. A ceremony is finished once (its row is deleted as it
-- is read) and expires after five minutes; expired rows are deleted when a new
-- ceremony begins.
CREATE TABLE account_passkey_ceremonies (
    token_hash bytea PRIMARY KEY CHECK (octet_length(token_hash) = 32),
    account_id bigint NOT NULL REFERENCES accounts ON DELETE CASCADE,
    purpose text NOT NULL CHECK (purpose IN ('register', 'authenticate')),
    session_hash bytea NOT NULL CHECK (octet_length(session_hash) = 32),
    state jsonb NOT NULL,
    expires_at timestamptz NOT NULL
);
CREATE INDEX account_passkey_ceremonies_expiry ON account_passkey_ceremonies (expires_at);

-- Set when a passkey is disabled as a suspected copy and the account is left with no
-- usable second factor and no recovery code, under `AfterSuspectedCopy::LockUntilRecovery`
-- (the default): every sign-in is refused until `Mfa::clear_recovery_lock` clears it.
-- Adding a nullable column with no default rewrites nothing.
ALTER TABLE accounts ADD COLUMN mfa_recovery_locked_at timestamptz;
